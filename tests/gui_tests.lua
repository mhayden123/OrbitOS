local fixture=require("gui_fixture")
local M={}
function M.run(test,equal)
  test("GUI: complete keyboard-only excavation wizard on a basic pocket",function()
    local f=fixture.new(26,20,false)
    f.localJob()
    equal(f.app.page,"review2"); assert(not f.app.gui.find("next").enabled)
    f.activate("checked"); f.activate("next")
    equal(f.app.page,"pending"); equal(#f.sent,1)
    local job=f.sent[1].body
    equal(job.spec.width,3); equal(job.spec.length,3); equal(job.spec.depth,2)
    equal(job.pose.frame,"local"); equal(job.pose.y,0); equal(job.verifyGPS,false)
    f.client.receive(7,{version=1,group="quarry",kind="ack",request=job.request,ok=true})
    f.event("timer",1); equal(f.app.page,"detail")
  end)
  test("GUI: clickable world-coordinate job, direction, GPS, and negative corners",function()
    local f=fixture.new(); f.status(7); f.render()
    f.click("turtle:7"); f.click("new"); f.click("flatten"); f.click("next")
    f.type("x","-10"); f.type("y","81"); f.type("z","-20"); f.click("next")
    assert(not f.app.gui.find("next").enabled)
    f.click("heading:1"); f.click("gps"); f.click("next")
    equal(f.app.draft.x1,"-10"); equal(f.app.draft.z1,"-20")
    f.click("next"); f.type("x2","-6"); f.type("z2","-17"); f.type("floorY","64")
    f.click("next"); equal(f.app.plan.total,320)
    f.click("next"); f.click("checked"); f.click("next")
    local body=f.sent[1].body
    equal(body.pose.heading,1); equal(body.pose.x,-10); equal(body.spec.floorY,64); equal(body.verifyGPS,true)
  end)
  test("GUI: all wizard screens fit 26x19, 26x20, and 51x19 displays",function()
    for _,size in ipairs({{26,19},{26,20},{51,19}}) do for _,color in ipairs({false,true}) do
      local f=fixture.new(size[1],size[2],color,true)
      f.type("group","quarry"); f.activate("next"); equal(f.saved,"quarry")
      f.open(); f.activate("flatten"); f.activate("next")
      f.type("x","-30000000"); f.type("y","30000"); f.type("z","-30000000"); f.activate("next")
      f.activate("heading:0"); f.activate("next"); f.activate("next")
      f.type("x2","-29999999"); f.type("z2","-29999999"); f.type("floorY","29998")
      f.activate("next")
      assert(f.screen.text():find("X -30000000..-29999999",1,true))
      f.activate("next"); assert(f.screen.text():find("KEEP floor Y 29998",1,true))
      f.event("key",f.keys.escape); equal(f.app.page,"review1")
    end end
  end)
  test("GUI: status refresh and back navigation preserve edits and cursor",function()
    local f=fixture.new(); f.open(); f.activate("quarry"); f.activate("local"); f.activate("next")
    f.type("width","16"); f.event("key",f.keys.left)
    f.status(7,{fuel=2000}); f.event("rednet_message",7,{})
    equal(f.app.gui.focus,"width"); equal(f.app.gui.cursors.width,1)
    f.event("char","2"); equal(f.app.draft.width,"126")
    f.event("key",f.keys.escape); equal(f.app.page,"placement")
    f.activate("next"); equal(f.app.draft.width,"126")
  end)
  test("GUI: keyboard editing, paste validation and error messages retain draft",function()
    local f=fixture.new(); f.open(); f.activate("quarry"); f.activate("local"); f.activate("next")
    f.type("width","16"); f.event("paste","oops"); equal(f.app.draft.width,"16")
    f.event("key",f.keys.home); f.event("key",f.keys.delete); equal(f.app.draft.width,"6")
    f.event("key",f.keys["end"]); f.event("key",f.keys.backspace); equal(f.app.draft.width,"")
    f.type("width","257"); f.activate("next"); equal(f.app.page,"info")
    assert(f.screen.text():find("Width: 1 to 256",1,true))
    f.activate("back"); equal(f.app.draft.width,"257"); equal(f.app.page,"dimensions")
  end)
  test("GUI: long editable fleet names scroll within their field",function()
    local f=fixture.new(26,20,false,true)
    f.type("group","abcdefghijklmnopqrstuvwxyz123456")
    equal(#f.app.group,32); f.activate("next"); equal(f.saved,"abcdefghijklmnopqrstuvwxyz123456")
  end)
  test("GUI: live pagination keeps focus attached to the same turtle ID",function()
    local f=fixture.new()
    for id=10,20 do f.status(id) end
    f.render(); f.focus("turtle:13")
    f.status(1); f.render(); equal(f.app.gui.focus,"turtle:13"); equal(f.app.listPage,2)
    f.activate("more"); equal(f.app.listPage,3)
    f.activate("prev"); equal(f.app.listPage,2)
    f.event("mouse_scroll",-1); equal(f.app.listPage,1)
  end)
  test("GUI: stale, foreign and incapable turtles disable physical controls",function()
    for _,change in ipairs({{owner=99},{mining=false},{}}) do
      local f=fixture.new(); f.status(7,change); f.render(); f.activate("turtle:7")
      if not change.owner and change.mining==nil then f.now=9; f.render() end
      assert(not f.app.gui.find("new").enabled)
      f.click("new"); equal(f.app.page,"detail"); equal(#f.sent,0)
    end
  end)
  test("GUI: changed session prevents submitting a previously reviewed job",function()
    local f=fixture.new(); f.localJob(); f.activate("checked")
    f.status(7,{session="rebooted"}); f.render(); f.activate("next")
    equal(#f.sent,0); equal(f.app.page,"info")
  end)
  test("GUI: cancel is confirmed and remains tied to its original job",function()
    local f=fixture.new(); f.status(7,{active=true,state="running",jobId="job-a",done=4,total=18})
    f.render(); f.click("turtle:7"); f.click("cancel"); equal(f.app.page,"cancel")
    f.click("back"); equal(#f.sent,0)
    f.click("cancel"); f.status(7,{active=true,state="running",jobId="job-b"}); f.render()
    f.click("next"); equal(f.sent[1].body.jobId,"job-a")
  end)
  test("GUI: pause/resume controls follow live state",function()
    local f=fixture.new(); f.status(7,{active=true,state="paused",jobId="work"}); f.render()
    f.activate("turtle:7"); equal(f.app.gui.find("control").label,"Resume")
    f.activate("control"); equal(f.sent[1].body.action,"resume")
  end)
  test("GUI: long status details remain accessible through pages",function()
    local f=fixture.new(); f.status(7,{reason=string.rep("Obstruction details. ",50)}); f.render()
    f.activate("turtle:7"); f.activate("details"); f.activate("next")
    equal(f.app.infoPage,2); f.activate("back"); equal(f.app.page,"detail")
  end)
  test("GUI: resize retains input; undersized displays cannot activate hidden buttons",function()
    local f=fixture.new(); f.open(); f.activate("quarry"); f.activate("local"); f.activate("next")
    f.type("width","16")
    f.screen.resize(20,12); f.event("term_resize"); equal(#f.app.gui.widgets,0)
    f.event("mouse_click",1,20,10); equal(#f.sent,0)
    f.screen.resize(51,19); f.event("term_resize"); equal(f.app.draft.width,"16")
    assert(f.app.gui.find("next"))
  end)
  test("GUI: unchanged frames do not rewrite the display",function()
    local f=fixture.new(); local count=f.screen.writes; f.render(); equal(f.screen.writes,count)
  end)
  test("GUI: held Enter cannot activate buttons on successive pages",function()
    local f=fixture.new(); f.open()
    f.event("key",f.keys.enter,true); equal(f.app.page,"program")
    f.activate("quarry"); f.event("key",f.keys.enter,true); equal(f.app.page,"mode")
  end)
  test("GUI: resize from a small screen repaints its unchanged header",function()
    local f=fixture.new()
    f.screen.resize(26,15); f.event("term_resize")
    f.screen.resize(26,20); f.event("term_resize")
    assert(f.screen.rows[1].text:find("TURTLE FLEET",1,true))
  end)
  test("client: acknowledgement retries retain request ID and heartbeats continue",function()
    local f=fixture.new(); f.localJob(); f.activate("checked"); f.activate("next")
    local request=f.sent[1].body.request
    for time=0,6 do f.now=time; f.client.tick(); f.event("timer",1) end
    local attempts,heartbeats=0,0
    for _,packet in ipairs(f.sent) do
      if packet.kind=="command" then attempts=attempts+1; equal(packet.body.request,request)
      elseif packet.kind=="heartbeat" then heartbeats=heartbeats+1 end
    end
    equal(attempts,3); assert(heartbeats>=3); equal(f.app.page,"info")
    assert(f.screen.text():find("Outcome unknown",1,true))
  end)
  test("client: ignores foreign acknowledgements and cancels retry after reboot",function()
    local f=fixture.new(); f.localJob(); f.activate("checked"); f.activate("next")
    f.client.receive(99,{version=1,group="quarry",kind="ack",request=f.sent[1].body.request,ok=true})
    assert(f.client.pending)
    f.status(7,{session="new-boot"}); assert(not f.client.pending); equal(f.client.result.ok,false)
    f.event("timer",1); equal(f.app.page,"info")
  end)
end
return M
