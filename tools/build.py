"""Bundle Lua modules and a universal offline installer for CraftOS."""
from pathlib import Path
import re
import zipfile
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
settings = json.loads((ROOT / "release.json").read_text(encoding="utf-8"))
VERSION = settings["fleetVersion"]
os_version = settings["orbitVersion"]
for version in (VERSION, os_version):
    assert re.fullmatch(r"[0-9]{1,4}\.[0-9]{1,4}\.[0-9]{1,4}", version), "Invalid release version"
assert settings["updateSource"].startswith("https://"), "Use an HTTPS default update source"
# Every registered built-in app is part of the same verified, rollbackable OS bundle.
app_source = (ROOT / "src/orbit/apps.lua").read_text(encoding="utf-8")
app_versions = [{"id": app_id, "title": title, "version": VERSION if app_id == "fleet" else os_version}
                for app_id, title in re.findall(r'definitions\[#definitions\+1\]=\{id="([\w-]+)",title="([^"]+)"', app_source)]
assert app_versions and len({a["id"] for a in app_versions}) == len(app_versions)
metadata = ('-- Generated by tools/build.py from release.json and the app registry.\nreturn {version=' +
            json.dumps(os_version) + ',updateSource=' + json.dumps(settings["updateSource"]) + ',apps={\n' +
            ',\n'.join('{id=' + json.dumps(a["id"]) + ',title=' + json.dumps(a["title"]) +
                       ',version=' + json.dumps(a["version"]) + '}' for a in app_versions) + '\n}}\n')
(ROOT / "src/orbit/release.lua").write_text(metadata, encoding="utf-8", newline="\n")
DIST.mkdir(exist_ok=True)
modules = {f"fleet.{path.stem}": path.read_text(encoding="utf-8")
           for path in (ROOT / "src" / "fleet").glob("*.lua")}
modules.update({f"orbit.{path.stem}": path.read_text(encoding="utf-8")
                for path in (ROOT / "src" / "orbit").glob("*.lua")})


def bundle(main, title=None):
    needed = set()

    def include_dependencies(source):
        for name in re.findall(r'require\("((?:fleet|orbit)\.[^"]+)"\)', source):
            if name not in needed:
                needed.add(name)
                if name not in ("fleet.payloads", "orbit.payload"):
                    include_dependencies(modules[name])

    include_dependencies(main)
    lines = [f"-- {title or ('Turtle Fleet ' + VERSION)} | Generated by tools/build.py; edit src/ instead.\n",
             "local factories, loaded = {}, {}\n",
             "local nativeRequire = require\n",
             "local function require(name)\n",
             "  if loaded[name] then return loaded[name] end\n",
             "  if not factories[name] then return nativeRequire(name) end\n",
             "  loaded[name] = factories[name]()\n",
             "  return loaded[name]\nend\n"]
    for name in sorted(needed):
        lines += [f'factories["{name}"] = function()\n', modules[name], "\nend\n"]
    return "".join(lines) + main


def lua_string(source):
    equals = ""
    while f"]{equals}]" in source:
        equals += "="
    return f"[{equals}[{source}]{equals}]"


payloads = {}
for role in ("controller", "worker"):
    payloads[role] = bundle((ROOT / "src" / f"{role}.lua").read_text(encoding="utf-8"))
    (DIST / f"fleet-{role}.lua").write_text(payloads[role], encoding="utf-8", newline="\n")

# This virtual module is generated, never copied from a previous release.
modules["fleet.payloads"] = "return {\n" + ",\n".join(
    f"{role} = {lua_string(source)}" for role, source in payloads.items()) + "\n}\n"
installer = bundle((ROOT / "src" / "installer_main.lua").read_text(encoding="utf-8"))
# Keep the ready-to-copy installer at the project root as well as in the release.
# The source entry point deliberately has a different name to avoid confusion.
(ROOT / "install.lua").write_text(installer, encoding="utf-8", newline="\n")
(DIST / "install.lua").write_text(installer, encoding="utf-8", newline="\n")

orbit = bundle((ROOT / "src/orbit_main.lua").read_text(encoding="utf-8"), f"Orbit OS {os_version}")
release = DIST / "orbit-release"
release.mkdir(exist_ok=True)
for path in (ROOT / "orbit.lua", DIST / "orbit.lua", release / "orbit.lua"):
    path.write_text(orbit, encoding="utf-8", newline="\n")
manifest = {"format": 1, "product": "orbit-os", "version": os_version, "artifact": "orbit.lua",
            "size": len(orbit.encode("utf-8")), "sha256": hashlib.sha256(orbit.encode("utf-8")).hexdigest(), "apps": app_versions}
(release / "manifest.json").write_text(json.dumps(manifest, indent=2)+"\n", encoding="utf-8", newline="\n")
modules["orbit.payload"] = ("return {manifest={format=1,product=\"orbit-os\",version=\""+os_version+
    "\",artifact=\"orbit.lua\",size="+str(manifest["size"])+",sha256=\""+manifest["sha256"]+
    "\"},source="+lua_string(orbit)+"}\n")
os_installer = bundle((ROOT / "src/orbit_install.lua").read_text(encoding="utf-8"), f"Orbit OS installer {os_version}")
for path in (ROOT / "install-os.lua", DIST / "install-os.lua"):
    path.write_text(os_installer, encoding="utf-8", newline="\n")

with zipfile.ZipFile(DIST / "turtle-fleet.zip", "w", zipfile.ZIP_DEFLATED) as archive:
    for path in (DIST / "install.lua", DIST / "fleet-controller.lua", DIST / "fleet-worker.lua"):
        archive.write(path, path.name)
    if (ROOT / "README.md").exists():
        archive.write(ROOT / "README.md", "README.md")
    for preview in sorted((ROOT / "docs").glob("*.png")):
        archive.write(preview, f"docs/{preview.name}")
with zipfile.ZipFile(DIST / "orbit-os.zip", "w", zipfile.ZIP_DEFLATED) as archive:
    for path in (DIST / "orbit.lua", DIST / "install-os.lua"):
        archive.write(path, path.name)
    for path in sorted(release.iterdir()):
        archive.write(path, f"orbit-release/{path.name}")
    if (ROOT / "docs/ORBIT.md").exists():
        archive.write(ROOT / "docs/ORBIT.md", "README.md")
    if (ROOT / "docs/orbit-preview.png").exists():
        archive.write(ROOT / "docs/orbit-preview.png", "orbit-preview.png")
print("Built Fleet releases, Orbit OS, its standalone installer, and local/GitHub update release.")
